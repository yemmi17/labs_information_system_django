from django import forms

from .models import Employee


class EmployeeForm(forms.ModelForm):
    """Форма для создания и редактирования сотрудника."""

    class Meta:
        model = Employee
        fields = [
            "last_name",
            "first_name",
            "middle_name",
            "position",
            "address",
            "work_phone",
            "personal_phone",
        ]
